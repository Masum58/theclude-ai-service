# WHAT: Pydantic request/response schemas for the Video Q&A chat API endpoints
# WHY: Validates chat inputs (like session management) and structures the LLM responses.
#      Ensures clients can start new chat sessions or continue existing ones cleanly.
# INPUT: N/A (defines schema shapes)
# OUTPUT: N/A
# WHO CALLS: app/api/routes/video_qa.py (Phase 4)
# CONNECTED TO: app/graphs/qa_graph.py (Phase 3)

from pydantic import BaseModel, Field
from typing import Optional


class QARequest(BaseModel):
    """
    What this is:
        The expected request body when a user asks a question about a video.

    Why it exists:
        Validates that we have the video ID and the user's question.
        Note that 'session_id' is Optional. If the client does not send a session_id,
        it means this is a new chat, and our API route will generate a new session_id.
    """
    video_id: str = Field(..., min_length=1, description="The ID of the video being questioned")
    question: str = Field(..., min_length=1, description="The user's natural language question")
    session_id: Optional[str] = Field(
        None, 
        description="Optional session ID. If not provided, a new session will be created."
    )

    class Config:
        json_schema_extra = {
            "example": {
                "video_id": "abc123",
                "question": "What is capitulation?",
                "session_id": "optional_session_xyz123"
            }
        }


class QAResponse(BaseModel):
    """
    What this is:
        The response shape returned after executing the Q&A graph.

    Why it exists:
        Returns the generated answer to the user.
        Crucially, it also returns the 'session_id' (either the one the client passed,
        or the new one generated by the server) so the client can reuse it for follow-up questions.
    """
    session_id: str = Field(..., description="The session ID associated with this chat session")
    answer: Optional[str] = Field(None, description="The AI's generated response to the question")
    error_message: Optional[str] = Field(None, description="Detailed error description if Q&A failed")

    class Config:
        json_schema_extra = {
            "example": {
                "session_id": "session_xyz123",
                "answer": "Capitulation in crypto trading is extreme panic selling...",
                "error_message": None
            }
        }
